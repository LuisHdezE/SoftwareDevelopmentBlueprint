#!/usr/bin/env python3
"""Regression tests for generated, non-installed Claude Code bundle."""
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location("adapter",ROOT/"scripts/generate-claude-code-adapter.py")
g=importlib.util.module_from_spec(s)
s.loader.exec_module(g)
with tempfile.TemporaryDirectory() as tmp:
    a,b=Path(tmp)/"a",Path(tmp)/"b"
    m=g.generate(a)
    n=g.generate(b)
    assert m==n
    assert m["execution_authorized"] is False and m["automatic_adoption"] is False
    print("PASS deterministic manifest and no authorization")
    registry=json.loads((ROOT/"catalog/agent-policy-registry.proposal.json").read_text(encoding="utf-8"))
    agents=list((a/".claude/agents").glob("*.md"))
    assert len(agents)==len(registry["agents"])==12
    for role in registry["agents"]:
        name="bf-"+role["alias"].removeprefix("@")
        raw=(a/".claude/agents"/(name+".md")).read_text(encoding="utf-8")
        assert ("name: "+name+"\n") in raw
        assert (ROOT/role["contract"]).read_text(encoding="utf-8") in raw
    print("PASS 12 canonical agent definitions")
    for path,sha in m["files"].items():
        assert hashlib.sha256((a/path).read_bytes()).hexdigest()==sha
        assert (a/path).read_bytes()==(b/path).read_bytes()
    print("PASS all generated bytes and digests")
    skills=list((a/".claude/skills").glob("*/SKILL.md"))
    assert skills
    print("PASS materialized skill count:",len(skills))
    try:g.generate(a)
    except ValueError:print("PASS existing output blocked")
    else:raise AssertionError("overwrites existing output")
    print("PASS Claude adapter generation (5 scenarios)")
